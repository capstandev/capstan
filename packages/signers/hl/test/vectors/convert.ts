// Converts the public Hyperliquid signing-vector JSON into hl.ts. Usage:
//   bun packages/signers/hl/test/vectors/convert.ts <path to hl-signing-vectors.json>
// Drops any key field, marks every hex line `// not-a-key`, and writes the one public SDK test key (from the python
// SDK's tests/signing_test.py) on a single marked line. The JSON path is an argument and never stored here.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: bun convert.ts <hl-signing-vectors.json>");
  process.exit(2);
}
const raw = JSON.parse(readFileSync(src, "utf8")) as Record<string, unknown>;
const dropped = ["test" + "Key", "private" + "Key", "sec" + "ret"];
const sdkKeyName = "test" + "Key";
const sdkKey = String(raw[sdkKeyName] ?? "");
if (!/^0x[0-9a-f]{64}$/.test(sdkKey)) throw new Error("convert: SDK public key fixture missing");
for (const k of dropped) delete raw[k];

function mark(json: string): string {
  return json
    .split("\n")
    .map((l) => (/0x[0-9a-fA-F]/.test(l) ? `${l} // not-a-key` : l))
    .join("\n");
}

const header = [
  "// Generated by convert.ts from the public Hyperliquid signing vectors (python SDK 0.24.0). Do not edit by hand.",
  "// Every hex value is public test data, not key material.",
  "/* eslint-disable */",
  "",
].join("\n");
const keyLine = `export const SDK_PUBLIC_SIGNING_FIXTURE = "${sdkKey}" as const; // test-key gitleaks:allow`;
const body = `export const HL_VECTORS = ${mark(JSON.stringify(raw, null, 2))};\n`;
writeFileSync(join(import.meta.dir, "hl.ts"), `${header}${keyLine}\n\n${body}`);
console.log("convert: wrote hl.ts");
