// Converts the B2 spike vectors JSON (entries {chain, txType, txInfo, txHash, pubKey}) into test/vectors/lighter.ts:
// one entry per line, every line ending `// not-a-key` (pubKey and txHash are public hex). Only these five fields
// are copied; any other field in the input (a key of any kind) is refused, not dropped silently.
// Usage: bun packages/signers/lighter-wasm/test/vectors/convert.ts <vectors.json>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FIELDS = ["chain", "txType", "txInfo", "txHash", "pubKey"] as const;

export function convert(json: string): string {
  const rows = JSON.parse(json) as Record<string, unknown>[];
  if (!Array.isArray(rows) || rows.length === 0) throw new Error("convert: expected a non-empty array");
  const lines = rows.map((r, i) => {
    const extra = Object.keys(r).filter((k) => !(FIELDS as readonly string[]).includes(k));
    if (extra.length) throw new Error(`convert: entry ${i} has unexpected fields ${extra.join(", ")}`);
    if (![304, 466324, 300].includes(r.chain as number)) throw new Error(`convert: entry ${i} has chain ${String(r.chain)}`);
    const o = Object.fromEntries(FIELDS.map((f) => [f, r[f]]));
    return `  ${JSON.stringify(o)}, // not-a-key`;
  });
  return [
    "// Generated by test/vectors/convert.ts from the B2 spike vectors: lighter-go aefa968 wasm, a throwaway API key, 100 per",
    "// signing id (half create orders, half cancels). Public data only: no key of any kind is in this file.",
    "export interface LighterVector { chain: 304 | 466324 | 300; txType: 14 | 15; txInfo: string; txHash: string; pubKey: string }",
    "export const LIGHTER_VECTORS: LighterVector[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const src = process.argv[2];
  if (!src) throw new Error("usage: convert.ts <vectors.json>");
  const out = join(import.meta.dir, "lighter.ts");
  writeFileSync(out, convert(readFileSync(src, "utf8")));
  console.log(`convert: wrote ${out}`);
}
