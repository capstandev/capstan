// Generates the Merkle parity vectors shared with Solidity (contracts/test/MerkleParity.t.sol):
//   merkle.ts   (TypeScript, one hex value per line, each marked not-a-key)
//   merkle.json (Foundry reads it with vm.readFile; one tree per line, each line carries a "g" marker member)
// Usage: bun packages/receipts/test/vectors/gen.ts [outDir]   (default: this folder)
import { keccak_256 } from "@noble/hashes/sha3.js";
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { Hex } from "@capstan/schema";
import { buildTree, proofFor, toHex } from "../../src";

export interface MerkleVector {
  size: number;
  leaves: Hex[];
  root: Hex;
  proofs: Hex[][];
}

const FIXED_SIZES = [1, 2, 3, 4, 5, 7, 8, 9, 16, 31, 33, 100];

function mulberry(start: number): () => number {
  let a = start >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function vectorSizes(): number[] {
  const rand = mulberry(0x4d45524b);
  const extra = Array.from({ length: 8 }, () => 2 + Math.floor(rand() * 63));
  return [...FIXED_SIZES, ...extra];
}

export function makeVectors(): MerkleVector[] {
  return vectorSizes().map((size, t) => {
    const leaves = Array.from({ length: size }, (_, i) => toHex(keccak_256(new TextEncoder().encode(`capstan-merkle-vector:${t}:${i}`))));
    const tree = buildTree(leaves);
    return { size, leaves, root: tree.root, proofs: leaves.map((_, i) => proofFor(tree, i)) };
  });
}

const NK = "// not-a-key";

export function renderTs(vs: MerkleVector[]): string {
  const out: string[] = [];
  out.push("// Generated by gen.ts (bun packages/receipts/test/vectors/gen.ts). Do not edit. Public test data, no keys.");
  out.push('import type { Hex } from "@capstan/schema";');
  out.push("");
  out.push("export interface MerkleVector {");
  out.push("  size: number;");
  out.push("  leaves: Hex[];");
  out.push("  root: Hex;");
  out.push("  proofs: Hex[][];");
  out.push("}");
  out.push("");
  out.push("export const MERKLE_VECTORS: MerkleVector[] = [");
  for (const v of vs) {
    out.push("  {");
    out.push(`    size: ${v.size},`);
    out.push(`    root: "${v.root}", ${NK}`);
    out.push("    leaves: [");
    for (const l of v.leaves) out.push(`      "${l}", ${NK}`);
    out.push("    ],");
    out.push("    proofs: [");
    for (const p of v.proofs) {
      if (p.length === 0) {
        out.push("      [],");
        continue;
      }
      out.push("      [");
      for (const h of p) out.push(`        "${h}", ${NK}`);
      out.push("      ],");
    }
    out.push("    ],");
    out.push("  },");
  }
  out.push("];");
  return `${out.join("\n")}\n`;
}

export function renderJson(vs: MerkleVector[]): string {
  const lines = vs.map((v, i) => `${JSON.stringify({ g: NK, size: v.size, root: v.root, leaves: v.leaves, proofs: v.proofs })}${i < vs.length - 1 ? "," : ""}`);
  return `{"count":${vs.length},"trees":[\n${lines.join("\n")}\n]}\n`;
}

export function writeVectors(dir: string): void {
  const vs = makeVectors();
  writeFileSync(join(dir, "merkle.ts"), renderTs(vs));
  writeFileSync(join(dir, "merkle.json"), renderJson(vs));
}

if (import.meta.main) {
  const dir = resolve(process.argv[2] ?? import.meta.dir);
  writeVectors(dir);
  console.log(`gen: wrote merkle.ts and merkle.json (${vectorSizes().length} trees) to ${dir}`);
}
